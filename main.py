
import gradio as gr
import requests
import os
import mimetypes

# -----------------------------
# API Configuration
# -----------------------------

API_URL = "http://127.0.0.1:8000"

UPLOAD_URL = f"{API_URL}/api/v1/documents/ingest"
CHAT_URL = f"{API_URL}/api/v1/chat/message"


# -----------------------------
# Document Upload
# -----------------------------

def upload_document(file_path, chunking_strategy):

    if not file_path:
        return "Please select a document first."

    try:
        filename = os.path.basename(file_path)
        content_type = (
            mimetypes.guess_type(filename)[0]
            or "application/octet-stream"
        )

        with open(file_path, "rb") as file:
            response = requests.post(
                UPLOAD_URL,
                files={
                    "file": (filename, file, content_type)
                },
                data={
                    "chunking_strategy": chunking_strategy
                },
                timeout=120
            )

        response.raise_for_status()
        result = response.json()

        return (
            f"Document uploaded successfully!\n\n"
            f"Filename: {filename}\n"
            f"Backend response: {result}"
        )

    except requests.RequestException as error:
        return f"Upload failed: {error}"


# -----------------------------
# Chat: RAG + Interview Booking
# -----------------------------

def chat(message, history, session_id):

    if not message.strip():
        return history, "", session_id

    try:
        payload = {
            "message": message,
            "session_id": session_id,
            "top_k": 5
        }

        response = requests.post(
            CHAT_URL,
            json=payload,
            timeout=120
        )

        response.raise_for_status()
        result = response.json()

        # Save the session ID returned by backend
        session_id = result["session_id"]

        # Assistant response
        answer = result["message"]

        # Show intent
        intent = result.get("intent", "general")
        answer = f"**Intent:** {intent.upper()}\n\n{answer}"

        # Show booking information
        booking_id = result.get("booking_id")

        if booking_id:
            answer += f"\n\nBooking ID: {booking_id}"

        history = history + [
            {"role": "user", "content": message},
            {"role": "assistant", "content": answer}
        ]

        return history, "", session_id

    except requests.RequestException as error:

        error_message = f"Backend error: {error}"

        history = history + [
            {"role": "user", "content": message},
            {"role": "assistant", "content": error_message}
        ]

        return history, "", session_id


# -----------------------------
# Clear Conversation
# -----------------------------

def clear_chat():

    # A new session will be generated by the backend
    return [], None


# -----------------------------
# Gradio Interface
# -----------------------------

with gr.Blocks(title="AI Document Assistant") as demo:

    gr.Markdown(
        """
        # AI Document Assistant

        Upload research documents, ask questions, or schedule
        an interview using the same conversational interface.
        """
    )

    # Store session ID separately for each Gradio session
    session_state = gr.State(value=None)

    with gr.Tab("Document Upload"):

        gr.Markdown("### Upload your document")

        file_input = gr.File(
            label="Select PDF or TXT",
            file_types=[".pdf", ".txt"],
            type="filepath"
        )

        chunking_strategy = gr.Radio(
            choices=["recursive", "fixed"],
            value="recursive",
            label="Chunking Strategy"
        )

        upload_button = gr.Button(
            "Upload Document",
            variant="primary"
        )

        upload_output = gr.Textbox(
            label="Upload Status",
            lines=5
        )

        upload_button.click(
            fn=upload_document,
            inputs=[
                file_input,
                chunking_strategy
            ],
            outputs=upload_output
        )

    with gr.Tab("Chat Assistant"):

        gr.Markdown(
            """
            ### Chat with your AI Assistant

            You can ask questions about uploaded documents
            or start an interview booking conversation.
            """
        )

        chatbot = gr.Chatbot(
            label="Conversation",
            height=450
        )

        with gr.Row():

            message_input = gr.Textbox(
                placeholder="Ask about a document or schedule an interview...",
                label="Your Message",
                scale=5
            )

            send_button = gr.Button(
                "Send",
                variant="primary",
                scale=1
            )

        clear_button = gr.Button("Clear Conversation")

        # Send using Enter
        message_input.submit(
            fn=chat,
            inputs=[
                message_input,
                chatbot,
                session_state
            ],
            outputs=[
                chatbot,
                message_input,
                session_state
            ]
        )

        # Send using button
        send_button.click(
            fn=chat,
            inputs=[
                message_input,
                chatbot,
                session_state
            ],
            outputs=[
                chatbot,
                message_input,
                session_state
            ]
        )

        # Reset chat and session
        clear_button.click(
            fn=clear_chat,
            inputs=[],
            outputs=[
                chatbot,
                session_state
            ]
        )


# -----------------------------
# Launch Application
# -----------------------------

if __name__ == "__main__":

    demo.launch(
        server_name="127.0.0.1",
        server_port=7860,
        theme=gr.themes.Soft()
    )
